"""Database tables. All content is fictional training data; there is no real personal data."""
from datetime import datetime, timezone

from sqlalchemy import JSON, DateTime, ForeignKey, Integer, String, Text, UniqueConstraint
from sqlalchemy.orm import Mapped, mapped_column, relationship

from .db import Base


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


class Guest(Base):
    __tablename__ = "guests"

    id: Mapped[str] = mapped_column(String(36), primary_key=True)
    token_hash: Mapped[str] = mapped_column(String(64), nullable=False)  # sha256 of the bearer token
    display_name: Mapped[str] = mapped_column(String(40), default="")
    xp: Mapped[int] = mapped_column(Integer, default=0)
    extras: Mapped[dict] = mapped_column(JSON, default=dict)  # caseXp, phishing, logLab, activity (opaque, bounded)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow, onupdate=utcnow)

    sessions: Mapped[list["InvestigationSession"]] = relationship(cascade="all, delete-orphan", back_populates="guest")
    achievements: Mapped[list["Achievement"]] = relationship(cascade="all, delete-orphan", back_populates="guest")


class InvestigationSession(Base):
    __tablename__ = "investigation_sessions"
    __table_args__ = (UniqueConstraint("guest_id", "client_id", name="uq_session_client"),)

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    guest_id: Mapped[str] = mapped_column(ForeignKey("guests.id", ondelete="CASCADE"), index=True)
    client_id: Mapped[str] = mapped_column(String(80))  # the investigation id generated by the browser
    case_id: Mapped[str] = mapped_column(String(60))
    attempt: Mapped[int] = mapped_column(Integer, default=1)
    mode: Mapped[str] = mapped_column(String(16))
    status: Mapped[str] = mapped_column(String(16))
    elapsed_sec: Mapped[int] = mapped_column(Integer, default=0)
    started_at: Mapped[str] = mapped_column(String(40))
    updated_at: Mapped[str] = mapped_column(String(40))
    extra: Mapped[dict] = mapped_column(JSON, default=dict)  # timed, timeLimitSec, hintPenalty, reportId

    guest: Mapped[Guest] = relationship(back_populates="sessions")
    collected: Mapped[list["CollectedEvidence"]] = relationship(cascade="all, delete-orphan")
    notes: Mapped[list["Note"]] = relationship(cascade="all, delete-orphan")
    graph: Mapped["GraphSnapshot | None"] = relationship(cascade="all, delete-orphan", uselist=False)
    verdict: Mapped["Verdict | None"] = relationship(cascade="all, delete-orphan", uselist=False)
    hint_requests: Mapped[list["HintRequest"]] = relationship(cascade="all, delete-orphan")
    reports: Mapped[list["Report"]] = relationship(cascade="all, delete-orphan")


class CollectedEvidence(Base):
    __tablename__ = "collected_evidence"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    session_id: Mapped[int] = mapped_column(ForeignKey("investigation_sessions.id", ondelete="CASCADE"), index=True)
    evidence_id: Mapped[str] = mapped_column(String(40))
    inspected_only: Mapped[int] = mapped_column(Integer, default=0)  # 1 = inspected but not collected


class Note(Base):
    __tablename__ = "notes"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    session_id: Mapped[int] = mapped_column(ForeignKey("investigation_sessions.id", ondelete="CASCADE"), index=True)
    client_id: Mapped[str] = mapped_column(String(80))
    text: Mapped[str] = mapped_column(Text)
    evidence_id: Mapped[str | None] = mapped_column(String(40), nullable=True)
    created_at: Mapped[str] = mapped_column(String(40))


class GraphSnapshot(Base):
    __tablename__ = "graph_snapshots"

    session_id: Mapped[int] = mapped_column(ForeignKey("investigation_sessions.id", ondelete="CASCADE"), primary_key=True)
    data: Mapped[dict] = mapped_column(JSON)


class Verdict(Base):
    __tablename__ = "verdicts"

    session_id: Mapped[int] = mapped_column(ForeignKey("investigation_sessions.id", ondelete="CASCADE"), primary_key=True)
    verdict_id: Mapped[str] = mapped_column(String(60), default="")
    confidence: Mapped[int] = mapped_column(Integer, default=50)
    draft: Mapped[dict] = mapped_column(JSON)


class Report(Base):
    """A report exactly as computed by the browser's deterministic scoring engine. Stored, not recomputed."""

    __tablename__ = "reports"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    session_id: Mapped[int] = mapped_column(ForeignKey("investigation_sessions.id", ondelete="CASCADE"), index=True)
    client_id: Mapped[str] = mapped_column(String(80))
    score: Mapped[int] = mapped_column(Integer)
    grade: Mapped[str] = mapped_column(String(4))
    xp_earned: Mapped[int] = mapped_column(Integer, default=0)
    data: Mapped[dict] = mapped_column(JSON)


class Achievement(Base):
    __tablename__ = "achievements"
    __table_args__ = (UniqueConstraint("guest_id", "achievement_id", name="uq_guest_achievement"),)

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    guest_id: Mapped[str] = mapped_column(ForeignKey("guests.id", ondelete="CASCADE"), index=True)
    achievement_id: Mapped[str] = mapped_column(String(40))
    unlocked_at: Mapped[str] = mapped_column(String(40))

    guest: Mapped[Guest] = relationship(back_populates="achievements")


class HintRequest(Base):
    __tablename__ = "hint_requests"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    session_id: Mapped[int] = mapped_column(ForeignKey("investigation_sessions.id", ondelete="CASCADE"), index=True)
    hint_id: Mapped[str] = mapped_column(String(60))
    at: Mapped[str] = mapped_column(String(40))
